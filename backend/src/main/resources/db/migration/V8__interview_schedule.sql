-- 仅由服务器发布步骤显式执行；本机不执行迁移或启动数据库。
CREATE TABLE interview_event (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    target_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    target_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    title VARCHAR(200) NOT NULL,
    round_name VARCHAR(100) NOT NULL,
    location VARCHAR(500) NOT NULL,
    meeting_url VARCHAR(2000) NOT NULL,
    notes MEDIUMTEXT NOT NULL,
    local_start DATETIME NOT NULL,
    zone_id VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    utc_offset VARCHAR(9) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    start_at DATETIME(6) NOT NULL,
    end_at DATETIME(6) NOT NULL,
    duration_minutes INT NOT NULL,
    remind_before_minutes INT NOT NULL,
    remind_at DATETIME(6) NOT NULL,
    reminder_acknowledged_at DATETIME(6) NULL,
    status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    revision BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_interview_event_owner (owner_id,id),
    KEY ix_interview_event_start (owner_id,start_at,id),
    KEY ix_interview_event_status_start (owner_id,status,start_at,id),
    KEY ix_interview_event_target_start (owner_id,target_id,start_at,id),
    KEY ix_interview_event_reminder (owner_id,status,reminder_acknowledged_at,remind_at,id),
    CONSTRAINT fk_interview_event_owner FOREIGN KEY (owner_id) REFERENCES owner_workspace (owner_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_interview_event_target FOREIGN KEY (owner_id,target_id,target_version_id) REFERENCES preparation_version (owner_id,item_id,id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_interview_event_target CHECK ((target_id IS NULL AND target_version_id IS NULL) OR (target_id IS NOT NULL AND target_version_id IS NOT NULL)),
    CONSTRAINT ck_interview_event_title CHECK (CHAR_LENGTH(TRIM(title)) BETWEEN 1 AND 200),
    CONSTRAINT ck_interview_event_notes CHECK (CHAR_LENGTH(notes) <= 10000),
    CONSTRAINT ck_interview_event_zone CHECK (CHAR_LENGTH(zone_id) BETWEEN 1 AND 100),
    CONSTRAINT ck_interview_event_offset CHECK (CHAR_LENGTH(utc_offset) BETWEEN 1 AND 9),
    CONSTRAINT ck_interview_event_local_minute CHECK (SECOND(local_start)=0),
    CONSTRAINT ck_interview_event_time CHECK (start_at < end_at AND remind_at <= start_at),
    CONSTRAINT ck_interview_event_duration CHECK (duration_minutes BETWEEN 1 AND 1440),
    CONSTRAINT ck_interview_event_lead CHECK (remind_before_minutes BETWEEN 0 AND 10080),
    CONSTRAINT ck_interview_event_status CHECK (status IN ('PLANNED','COMPLETED','CANCELLED')),
    CONSTRAINT ck_interview_event_revision CHECK (revision BETWEEN 0 AND 9007199254740991)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- 保存当时完整展示快照及独立目标外键；来源状态变化不改写旧修订。
CREATE TABLE interview_event_history (
    owner_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    revision BIGINT NOT NULL,
    action VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    target_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    target_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    title VARCHAR(200) NOT NULL,
    start_at DATETIME(6) NOT NULL,
    status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    reason VARCHAR(2000) NOT NULL,
    snapshot_json MEDIUMTEXT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (event_id,revision),
    UNIQUE KEY uk_interview_history_owner (owner_id,event_id,revision),
    CONSTRAINT fk_interview_history_event FOREIGN KEY (owner_id,event_id) REFERENCES interview_event (owner_id,id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_interview_history_target FOREIGN KEY (owner_id,target_id,target_version_id) REFERENCES preparation_version (owner_id,item_id,id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_interview_history_target CHECK ((target_id IS NULL AND target_version_id IS NULL) OR (target_id IS NOT NULL AND target_version_id IS NOT NULL)),
    CONSTRAINT ck_interview_history_revision CHECK (revision BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_interview_history_title CHECK (CHAR_LENGTH(TRIM(title)) BETWEEN 1 AND 200),
    CONSTRAINT ck_interview_history_action CHECK (action IN ('CREATED','UPDATED','RESCHEDULED','CANCELLED','COMPLETED','ACKNOWLEDGED')),
    CONSTRAINT ck_interview_history_initial CHECK ((revision=0 AND action='CREATED') OR (revision>0 AND action<>'CREATED')),
    CONSTRAINT ck_interview_history_state CHECK (
      (action IN ('CREATED','UPDATED','RESCHEDULED','ACKNOWLEDGED') AND status='PLANNED')
      OR (action='CANCELLED' AND status='CANCELLED') OR (action='COMPLETED' AND status='COMPLETED')),
    CONSTRAINT ck_interview_history_reason CHECK (action NOT IN ('RESCHEDULED','CANCELLED') OR CHAR_LENGTH(TRIM(reason)) > 0),
    CONSTRAINT ck_interview_history_json CHECK (JSON_VALID(snapshot_json) AND JSON_TYPE(CAST(snapshot_json AS JSON))='OBJECT')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- 确切材料关系按修订保留，类型分别绑定准备／知识版本，不能只从快照 JSON 反查来源。
CREATE TABLE interview_event_material (
    owner_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    event_revision BIGINT NOT NULL,
    ordinal INT NOT NULL,
    source_kind VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    preparation_source_item_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    preparation_source_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    knowledge_source_item_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    knowledge_source_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    PRIMARY KEY (event_id,event_revision,ordinal),
    UNIQUE KEY uk_interview_material_preparation (event_id,event_revision,source_kind,preparation_source_item_id,preparation_source_version_id),
    UNIQUE KEY uk_interview_material_knowledge (event_id,event_revision,source_kind,knowledge_source_item_id,knowledge_source_version_id),
    KEY ix_interview_material_preparation (owner_id,preparation_source_item_id,preparation_source_version_id,event_id),
    KEY ix_interview_material_knowledge (owner_id,knowledge_source_item_id,knowledge_source_version_id,event_id),
    CONSTRAINT fk_interview_material_history FOREIGN KEY (owner_id,event_id,event_revision) REFERENCES interview_event_history (owner_id,event_id,revision) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_interview_material_preparation FOREIGN KEY (owner_id,preparation_source_item_id,preparation_source_version_id) REFERENCES preparation_version (owner_id,item_id,id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_interview_material_knowledge FOREIGN KEY (owner_id,knowledge_source_item_id,knowledge_source_version_id) REFERENCES knowledge_version (owner_id,item_id,id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_interview_material_ordinal CHECK (ordinal BETWEEN 0 AND 49),
    CONSTRAINT ck_interview_material_source CHECK (
      (source_kind IN ('PROJECT','FACT','EXPRESSION') AND preparation_source_item_id IS NOT NULL AND preparation_source_version_id IS NOT NULL AND knowledge_source_item_id IS NULL AND knowledge_source_version_id IS NULL)
      OR (source_kind='KNOWLEDGE' AND preparation_source_item_id IS NULL AND preparation_source_version_id IS NULL AND knowledge_source_item_id IS NOT NULL AND knowledge_source_version_id IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
